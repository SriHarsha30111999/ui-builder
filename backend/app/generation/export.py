"""Download of a Generated Project version as a runnable project (zip).

Layout of the archive (one root folder, `generated-ui-v<N>/`):

    package.json        runnable: dev / build / preview scripts and the pinned toolchain
    tsconfig.json  vite.config.ts  index.html
    src/main.tsx  src/App.tsx  src/**   Generated Source Code written by the model
    README.md  .gitignore

Only the stored source is exported (never dist/, node_modules or anything the build left behind), only regular files, and
only the known top-level names plus `src/`.
"""
import io
import json
import zipfile
from pathlib import Path

TOP_LEVEL = ("tsconfig.json", "vite.config.ts", "index.html")
MAX_EXPORT_BYTES = 5 * 1024 * 1024

# Same pins as backend/sandbox/package.json (the toolchain the build uses), so a downloaded project builds like the Preview did.
PACKAGE = {
    "name": "generated-ui",
    "private": True,
    "version": "0.0.0",
    "type": "module",
    "scripts": {"dev": "vite", "build": "tsc --noEmit && vite build", "preview": "vite preview"},
    "dependencies": {"react": "^19.3.0", "react-dom": "^19.3.0"},
    "devDependencies": {
        "@types/react": "^19.3.0",
        "@types/react-dom": "^19.3.0",
        "@vitejs/plugin-react": "^6.1.2",
        "typescript": "^6.0.3",
        "vite": "^8.3.4",
    },
}

README = """# Generated UI (version {n})

React + TypeScript + Vite project generated by the UI Builder.

    npm install
    npm run dev       # development server
    npm run build     # type-check and production build into dist/

Source is in `src/` (entry: `src/main.tsx`, root component: `src/App.tsx`).
"""

GITIGNORE = "node_modules\ndist\n"


class ExportError(Exception):
    pass


def collect(base: Path) -> dict[str, bytes]:
    """Relative path -> content of everything that belongs in the archive."""
    files: dict[str, bytes] = {}
    total = 0
    candidates = [base / name for name in TOP_LEVEL]
    src = base / "src"
    if src.is_dir():
        candidates += [p for p in sorted(src.rglob("*"))]
    for p in candidates:
        if p.is_symlink() or not p.is_file():
            continue
        data = p.read_bytes()
        total += len(data)
        if total > MAX_EXPORT_BYTES:
            raise ExportError("The source is too large to export.")
        files[p.relative_to(base).as_posix()] = data
    if not any(k.startswith("src/") for k in files):
        raise ExportError("The stored source for this version is missing.")
    return files


def build_zip(base: Path, version_number: int) -> bytes:
    root = f"generated-ui-v{version_number}"
    files = collect(base)
    files["package.json"] = (json.dumps(PACKAGE, indent=2) + "\n").encode()
    files["README.md"] = README.format(n=version_number).encode()
    files[".gitignore"] = GITIGNORE.encode()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in sorted(files):
            z.writestr(f"{root}/{rel}", files[rel])
    return buf.getvalue()
